def _current_title(mw):
    lw = mw.findChild(QListWidget)
    if lw is not None and lw.currentItem() is not None:
        return lw.currentItem().text().strip()
    return ""


def _clean_title(title: str) -> str:
    """Убирает ТОЛЬКО ведущую эмодзи/иконку: '🔔 Уведомления' → 'Уведомления'.
    Пробелы и слэши ВНУТРИ названия ('Музыка/DJ', 'Входы/Выходы') сохраняет."""
    return re.sub(r"^[^0-9A-Za-zА-Яа-яЁё]+", "", title).strip()


def _active_subtab_title(mw) -> str:
    """Инструкция активной подвкладки. Если для самой вложенной подвкладки
    нет текста — откат на внешнюю вкладку (старое поведение, без заглушки)."""
    stack = getattr(mw, "stack", None)
    if stack is None:
        return ""
    cur = stack.currentWidget()
    if cur is None:
        return ""
    from PyQt6.QtWidgets import QTabWidget
    tabs = []
    for tw in cur.findChildren(QTabWidget):
        depth, pp = 0, tw.parentWidget()
        while pp is not None:
            depth += 1
            pp = pp.parentWidget()
        tabs.append((depth, tw))
    tabs.sort(key=lambda x: x[0])  # от внешних к вложенным
    titles = [_clean_title(tw.tabText(tw.currentIndex())) for _, tw in tabs if tw.count()]
    for t in reversed(titles):  # сначала самая вложенная
        if t in HELP_TEXTS or t in _ALIASES:
            return t
    return titles[-1] if titles else ""  # внешняя вкладка — как раньше


def show_help(mw):
    """Открывает прокручиваемое окно инструкции вместо QMessageBox.
    В хабах — инструкция активной ПОДВКЛАДКИ, не общая."""
    title = _active_subtab_title(mw) or _clean_title(_current_title(mw))
    title = _ALIASES.get(title, title)
    text = HELP_TEXTS.get(title, DEFAULT_HELP)
    dlg = QDialog(mw)
    dlg.setWindowTitle("Инструкция: " + (title or "экран"))
    dlg.resize(750, 650)
    dlg.setMinimumSize(700, 550)
    dlg.setStyleSheet("""
        QDialog { background-color: #0f172a; }
        QTextEdit { background: #1e293b; border: 1px solid #334155; border-radius: 8px; padding: 12px; color: #e2e8f0; font-family: 'Segoe UI', sans-serif; font-size: 13px; }
        QPushButton { background: linear-gradient(135deg, #06b6d4, #0891b2); border: none; border-radius: 6px; padding: 10px 32px; font-weight: 600; color: white; }
        QPushButton:hover { opacity: 0.85; }
    """)
    v = QVBoxLayout(dlg)
    v.setContentsMargins(16, 16, 16, 16)
    te = QTextEdit()
    if text.lstrip().startswith("<"):
        te.setHtml(text)
    else:
        te.setPlainText(text)
    te.setReadOnly(True)
    v.addWidget(te, 1)
    b = QPushButton("Закрыть")
    b.clicked.connect(dlg.accept)
    v.addWidget(b)
    dlg.exec()


