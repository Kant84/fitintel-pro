import re, py_compile
PATH = "support_bot/app.py"
src = open(PATH, encoding="utf-8").read()

NEW_DOMAIN = "DOMAIN = {\"клиент\",\"абонемент\",\"платёж\",\"платеж\",\"оплат\",\"касс\",\"ккт\",\"чек\",\"турникет\",\"браслет\",\"вход\",\"визит\",\"расписан\",\"услуг\",\"тренер\",\"пользовател\",\"роль\",\"прав\",\"лиценз\",\"desktop\",\"программ\",\"сервер\",\"настройк\",\"уведомлен\",\"email\",\"смс\",\"max\",\"вендинг\",\"автомат\",\"магазин\",\"склад\",\"зарплат\",\"отчёт\",\"отчет\",\"face\",\"музык\",\"шкафчик\",\"rfid\",\"скуд\",\"ошибк\",\"обновлен\",\"установк\",\"qr\",\"замер\",\"фискальн\",\"атол\",\"банк\",\"юкасса\",\"лог\",\"доступ\",\"парол\",\"баланс\",\"кошелёк\",\"бонус\",\"скидк\",\"замороз\",\"списан\",\"возврат\",\"продл\",\"тариф\",\"сообщен\",\"чат\",\"аналит\",\"kpi\",\"api\",\"синхрон\",\"бэкап\",\"резервн\",\"регистрац\",\"токен\",\"рассылк\",\"инструкц\",\"гид\",\"экспорт\",\"excel\",\"pdf\",\"1с\",\"интеграц\",\"лимит\",\"зал\",\"счётчик\",\"счетчик\",\"кто\",\"двойн\",\"индикатор\",\"сохранени\",\"подключен\",\"профил\",\"печать\",\"шаблон\"}"
NEW_FR = "FRUSTRATED = {\"гонишь\",\"очумел\",\"бред\",\"чушь\",\"хрень\",\"ерунда\",\"отстой\",\"задолбал\",\"исправьте\",\"почините\",\"ты что\",\"вы что\",\"алле\",\"але\",\"эй\",\"слушай\",\"что за\",\"нифига\",\"капец\",\"бесит\",\"уроды\",\"тупой\",\"тупая\",\"кривой\",\"это ещё что\",\"возмутительно\"}"
NEW_ESC = "ESCALATE = {\"оператор\",\"живой\",\"живого\",\"человек\",\"специалист\",\"админ\",\"администратор\",\"свяжите\",\"свяжи\",\"позовите\",\"диспетчер\",\"горячая линия\",\"нужен человек\",\"соедините\",\"всё не работает\",\"все не работает\",\"ничего не работает\",\"не работает вообще\",\"полный сбой\"}"
NEW_OFF = 'OFFTOPIC_REPLY = "Не нашёл готового ответа в базе знаний. Уточните, пожалуйста, какая именно функция или экран не работает (например: касса, турникет, Face ID, клиенты, отчёты) — передам вопрос инженеру поддержки."'

for pat, new, name in [(r"DOMAIN = \{.*?\}", NEW_DOMAIN, "DOMAIN"),
                       (r"FRUSTRATED = \{.*?\}", NEW_FR, "FRUSTRATED"),
                       (r"ESCALATE = \{.*?\}", NEW_ESC, "ESCALATE")]:
    src, c = re.subn(pat, lambda m: new, src, count=1, flags=re.S)
    assert c == 1, name

anchor = "            return row[0], row[1], row[2], float(row[3])\n    return None"
assert src.count(anchor) == 1, "kb_search tail"
inject = ("            return row[0], row[1], row[2], float(row[3])\n"
          "        words = [w for w in q.split() if len(w) >= 4][:6]\n"
          "        if words:\n"
          "            cur.execute(\n"
          "                \"SELECT question, answer, screenshots, 0.0 FROM kb_articles \"\n"
          "                \"WHERE EXISTS (SELECT 1 FROM unnest(string_to_array(%s,' ')) w \"\n"
          "                \"              WHERE char_length(w) >= 4 AND (word_similarity(question, w) >= 0.55 \"\n"
          "                \"                   OR word_similarity(coalesce(keywords,''), w) >= 0.55)) \"\n"
          "                \"ORDER BY question LIMIT 1\", (q,))\n"
          "            row = cur.fetchone()\n"
          "            if row:\n"
          "                return row[0], row[1], row[2], 0.15\n"
          "    return None")
src = src.replace(anchor, inject, 1)

m = re.search(r"OFFTOPIC_REPLY\s*=\s*(\([^)]*\)|\"[^\"]*\"|'[^']*')", src, re.S)
assert m, "OFFTOPIC_REPLY"
src = src[:m.start()] + NEW_OFF + src[m.end():]

open(PATH, "w", encoding="utf-8", newline="\n").write(src)
py_compile.compile(PATH, doraise=True)
print("V23_PATCH_OK=1")
